-- 1. Create the registrations table
create table if not exists public.registrations (
  id bigint generated by default as identity primary key,
  created_at timestamptz default timezone('utc'::text, now()) not null,
  full_name text not null,
  email text not null,
  phone text,
  student_id text not null,
  faculty text not null
);

-- In case the table already exists, run this single line to add the phone column:
alter table public.registrations add column if not exists phone text;

-- 2. Enable Row Level Security (RLS)
alter table public.registrations enable row level security;

-- 3. Allow public registrations from students (Insert policy)
create policy "Allow anonymous registrations"
on public.registrations
for insert
with check (true);

-- 4. Allow reading registrations for the Admin Dashboard (Select policy)
create policy "Allow reading registrations"
on public.registrations
for select
using (true);

-- 5. Allow deleting registrations from the Admin Dashboard (Delete policy)
create policy "Allow deleting registrations"
on public.registrations
for delete
using (true);

